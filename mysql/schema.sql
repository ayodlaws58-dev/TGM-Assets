CREATE TABLE IF NOT EXISTS assets (
    seq BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
    asset_id VARCHAR(64) NOT NULL PRIMARY KEY,
    name TEXT NOT NULL,
    category VARCHAR(64) NOT NULL DEFAULT '',
    location TEXT NOT NULL,
    last_service VARCHAR(32) NOT NULL DEFAULT '',
    interval_days VARCHAR(32) NOT NULL DEFAULT '',
    notes TEXT NOT NULL
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS work_orders (
    seq BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
    wo_id VARCHAR(64) NOT NULL PRIMARY KEY,
    asset_id VARCHAR(64) NOT NULL DEFAULT '',
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    priority VARCHAR(32) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT '',
    assigned_to VARCHAR(64) NOT NULL DEFAULT '',
    created VARCHAR(32) NOT NULL DEFAULT '',
    due VARCHAR(32) NOT NULL DEFAULT '',
    completed VARCHAR(32) NOT NULL DEFAULT '',
    requested_by VARCHAR(64) NOT NULL DEFAULT '',
    cost VARCHAR(32) NOT NULL DEFAULT '',
    payment_status VARCHAR(32) NOT NULL DEFAULT '',
    paid_on VARCHAR(32) NOT NULL DEFAULT '',
    approval_status VARCHAR(32) NOT NULL DEFAULT '',
    approved_by VARCHAR(64) NOT NULL DEFAULT '',
    approved_on VARCHAR(32) NOT NULL DEFAULT '',
    decision_note TEXT NOT NULL
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS procurement (
    seq BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
    req_id VARCHAR(64) NOT NULL PRIMARY KEY,
    item TEXT NOT NULL,
    quantity VARCHAR(32) NOT NULL DEFAULT '',
    unit_cost VARCHAR(32) NOT NULL DEFAULT '',
    asset_id VARCHAR(64) NOT NULL DEFAULT '',
    wo_id VARCHAR(64) NOT NULL DEFAULT '',
    reason TEXT NOT NULL,
    requested_by VARCHAR(64) NOT NULL DEFAULT '',
    created VARCHAR(32) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT '',
    decided_by VARCHAR(64) NOT NULL DEFAULT '',
    decided_on VARCHAR(32) NOT NULL DEFAULT '',
    decision_note TEXT NOT NULL
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS users (
    seq BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
    username VARCHAR(64) NOT NULL PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL DEFAULT '',
    role VARCHAR(32) NOT NULL DEFAULT 'user',
    salt VARCHAR(64) NOT NULL DEFAULT '',
    hash VARCHAR(128) NOT NULL DEFAULT '',
    email VARCHAR(255) NOT NULL DEFAULT '',
    reset_hash VARCHAR(128) NOT NULL DEFAULT '',
    reset_expires VARCHAR(32) NOT NULL DEFAULT '',
    reset_attempts VARCHAR(8) NOT NULL DEFAULT ''
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS notifications (
    seq BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
    notif_id VARCHAR(64) NOT NULL PRIMARY KEY,
    username VARCHAR(64) NOT NULL DEFAULT '',
    kind VARCHAR(32) NOT NULL DEFAULT '',
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    created VARCHAR(32) NOT NULL DEFAULT '',
    `read` VARCHAR(8) NOT NULL DEFAULT '',
    `key` VARCHAR(255) NOT NULL DEFAULT ''
) CHARACTER SET utf8mb4
